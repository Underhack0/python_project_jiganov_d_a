#1. Дан список A размера N и целое число K (1 < K < N).
# Вывести элементы список с порядковыми номерами,
# кратными K: \(A_{K}\), \(A_{2*K}\), \(A_{3*K}\),... .
# Условный оператор не использовать.

N = int(input("Введите размер списка: "))
A = []
while len(A) != N:
    A.append(input("Введите следующий элемент списка: "))
K = input("K: ")
counter = 0

while type(K) != int:
    try:
        K = int(K)
    except ValueError:
        print("Неправильно ввели!")
        K = input("Введите первое число:")

for i in range(K - 1, N, K):
    print(A[i])