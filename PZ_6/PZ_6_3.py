# 1. Дан список размера N. Осуществить сдвиг элементов список вправо на одну позицию
# (при этом \(A_{1}\) перейдет в \(A_{2}\), \(A_{2}\) — в \(A_{3}\), ..., \(A_{N-1}\) — в \(A_{N}\),
# а исходное значение последнего элемента будет потеряно).
# Первый элемент полученного списка положить равным 0.

N = int(input("Введите размер списка: "))
lst = []
while len(lst) != N:
    lst.append(input("Введите следующий элемент списка: "))

count, counter = N, N

while count != 1:
    lst[count - 1] = lst[count - 2]
    count -= 1
    if count == 1:
        lst[0] = 0

print(lst)

