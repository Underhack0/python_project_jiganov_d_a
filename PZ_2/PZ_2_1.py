# Даны целые положительные числа A и B (A > B).
# На отрезке длины А размещено максимально возможное
# количество отрезков длины В. Используя операцию взятия остатка
# от деления нацело, найти длину незанятой части отрезка А.

A = int(input("A:"))
B = int(input("B:"))

if A > B: # проверка на разность
    print(f'\nДлина остатка: 0.{A % B}') # нахождение и вывод остатка
else:
    print("Err: Введены некорректные данные")