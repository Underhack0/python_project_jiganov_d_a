# 2. Дано целое число N (> 1). Найти наибольшее целое число К, при котором выполняется неравенство 3^K < N.


N = input("N: ")

while type(N) != int:
    try:
        N = int(N)
    except ValueError:
        print("Неправильно ввели!")
        N = input("Введите первое число:")
    if N <= 1:
        print("Неправильно ввели!")
        N = input("Введите первое число:")

K = 1

while (3 ** K) <= N:
    K += 1

print(K - 1)